import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'
async function login(page: Page, account: string) {
  await page.goto('/')
  await page.getByLabel('Email address').fill(account + '@e2e.stockflow.test')
  await page.getByLabel('Password', { exact: true }).fill(process.env.E2E_PASSWORD!)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Inventory overview' })).toBeVisible()
}
async function logout(page: Page) {
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Welcome back' })).toBeVisible()
}
test('real two-user transfer, balance conservation, ledger and mobile access', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  await login(page, 'manager')
  await expect(page.locator('.metric').filter({ hasText: 'Active products' })).toContainText('24')
  await expect(page.locator('.skeletons')).toHaveCount(0)
  await expect(page.locator('.metric').filter({ hasText: 'Stock positions' })).toContainText('72')
  await page.screenshot({ path: '../.local/phase4-overview-desktop.png', fullPage: true })
  await page.getByRole('navigation').getByRole('link', { name: 'Transfers', exact: true }).click()
  await page.getByRole('button', { name: 'New transfer' }).click()
  await page.getByLabel('Source store').selectOption({ label: 'Main Warehouse' })
  await page.getByLabel('Destination store').selectOption({ label: 'Downtown Branch' })
  await page
    .getByLabel('Product 1', { exact: true })
    .selectOption({ label: 'SF-001 · Desk notebook (unit)' })
  await page.getByLabel('Quantity 1', { exact: true }).fill('20.0000')
  await page.screenshot({ path: '../.local/phase6-transfer-draft.png', fullPage: true })
  await page.getByRole('button', { name: 'Save draft' }).click()
  await expect(page).toHaveURL(/\/transfers\/\d+$/)
  const transferUrl = page.url()
  await page.getByRole('button', { name: 'Submit for approval', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm submit' }).click()
  await expect(
    page.getByText('A different authorized person must approve this transfer.'),
  ).toBeVisible()
  await expect(page.getByRole('button', { name: 'Approve & post' })).toHaveCount(0)
  await page.screenshot({ path: '../.local/phase6-transfer-submitted.png', fullPage: true })
  await logout(page)
  await login(page, 'approver')
  await page.getByRole('navigation').getByRole('link', { name: 'Approvals', exact: true }).click()
  await page.getByRole('link', { name: /^TRF-/ }).click()
  await expect(page).toHaveURL(transferUrl)
  await page.getByRole('button', { name: 'Approve & post' }).click()
  await page.getByRole('button', { name: 'Confirm approve' }).click()
  await expect(page.locator('.page-title .badge')).toHaveText('approved posted')
  await page.screenshot({ path: '../.local/phase6-transfer-posted.png', fullPage: true })
  await page.reload()
  await expect(page.getByRole('button', { name: 'Approve & post' })).toHaveCount(0)
  await page.getByRole('navigation').getByRole('link', { name: 'Stock balances' }).click()
  await page.getByLabel('Product filter').selectOption({ label: 'SF-001 · Desk notebook' })
  await expect(page.locator('tbody tr')).toHaveCount(3)
  await expect(page.getByRole('row').filter({ hasText: 'Main Warehouse' })).toContainText('80.0000')
  await expect(page.getByRole('row').filter({ hasText: 'Downtown Branch' })).toContainText(
    '50.0000',
  )
  await page
    .getByRole('navigation')
    .getByRole('link', { name: 'Stock ledger', exact: true })
    .click()
  await expect(page).toHaveURL(/\/ledger/)
  await expect(page.getByRole('heading', { name: 'Stock ledger', exact: true })).toBeVisible()
  await page.getByLabel('Product filter').selectOption({ label: 'SF-001 · Desk notebook' })
  await expect(page.locator('tbody tr')).toHaveCount(5)
  await expect(page.getByRole('row').filter({ hasText: 'transfer out' })).toContainText('-20.0000')
  await expect(page.getByRole('row').filter({ hasText: 'transfer in' })).toContainText('20.0000')
  await page.screenshot({ path: '../.local/phase4-ledger-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('navigation').getByRole('link', { name: 'Overview', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Inventory overview' })).toBeVisible()
  await expect
    .poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    .toBe(true)
  await expect(page.locator('.skeletons')).toHaveCount(0)
  await page.screenshot({ path: '../.local/phase4-overview-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('navigation').getByRole('link', { name: 'Stock balances' }).click()
  await expect(page.getByRole('heading', { name: 'Inventory balances' })).toBeVisible()
  await expect(page.locator('.skeletons')).toHaveCount(0)
  await expect(page.locator('tbody tr').first()).toBeVisible()
  await expect
    .poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    .toBe(true)
  await page.screenshot({ path: '../.local/phase4-balances-mobile.png', fullPage: true })
  expect(errors).toEqual([])
})
